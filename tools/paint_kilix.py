#!/usr/bin/env python3
"""Copy Kilix Land's walk pair and Shellda's wizard into src/sprites.c.

Kilix Land walks the legend cast with columns 0 and 4 of each direction row
in assets/graphics/casts/legend-player.png. That sheet is the Legend of Kilix
player atlas. The wizard frame still comes from Shellda, with magenta key
fringe dropped.
"""

import pathlib
import sys

from PIL import Image

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import extract_sprites

CELL = 64
# Zelda-style feet sit on this source row of the 64x64 cell.
FOOT = 60
# Kilix Land facing rows: down, left, right, up. Zell's order is down, up,
# left, right. Columns 0 and 4 are the two frames Land alternates.
HERO = (
    ("SPR_KILIX_DOWN_0", 0, 0),
    ("SPR_KILIX_DOWN_1", 4, 0),
    ("SPR_KILIX_UP_0", 0, 6),
    ("SPR_KILIX_UP_1", 4, 6),
    ("SPR_KILIX_LEFT_0", 0, 2),
    ("SPR_KILIX_LEFT_1", 4, 2),
    ("SPR_KILIX_RIGHT_0", 0, 4),
    ("SPR_KILIX_RIGHT_1", 4, 4),
)


def key_fringe(pixel):
    """Magenta left on a sprite edge after the sheet was keyed and scaled."""
    alpha = (pixel >> 24) & 255
    if alpha < 128:
        return False
    red = (pixel >> 16) & 255
    green = (pixel >> 8) & 255
    blue = pixel & 255
    if red < 24 or blue < 24:
        return False
    spill = min(red, blue) - green
    gap = abs(red - blue)
    if spill > 55 and green < 90 and gap < 80:
        return True
    return green < 16 and spill > 24 and gap < 40


def drop_key_fringe(pixels):
    return [0 if key_fringe(pixel) else pixel for pixel in pixels]


def cell_pixels(image, column, row):
    crop = image.crop((
        column * CELL, row * CELL,
        (column + 1) * CELL, (row + 1) * CELL,
    ))
    pixels = []
    for red, green, blue, alpha in crop.getdata():
        if alpha < 128:
            pixels.append(0)
        else:
            pixels.append((0xFF << 24) | (red << 16) | (green << 8) | blue)
    if len(pixels) != CELL * CELL:
        raise SystemExit(f"cell {column},{row} has {len(pixels)} pixels")
    return pixels


def emit_array(name, pixels):
    lines = [f"static const uint32_t {name}[{len(pixels)}] = {{"]
    row = []
    for pixel in pixels:
        row.append(f"0x{pixel:08x}u")
        if len(row) == 8:
            lines.append("    " + ", ".join(row) + ",")
            row = []
    if row:
        lines.append("    " + ", ".join(row) + ",")
    lines.append("};")
    lines.append("")
    return lines


def emit(hero, wizard):
    lines = [
        "/* Generated by tools/paint_kilix.py. Do not edit by hand.",
        " * Kilix's frames are Kilix Land's legend-cast walk pair.",
        " * The wizard frame is copied from Shellda src/generated_sprites.h",
        " * (MIT, Copyright (c) 2026 shellda contributors).",
        " */",
        '#include "sprites.h"',
        "",
        "int zell_kilix_width(void) { return 64; }",
        "int zell_kilix_height(void) { return 64; }",
        f"int zell_kilix_foot(void) {{ return {FOOT}; }}",
        "int zell_wizard_width(void) { return 18; }",
        "int zell_wizard_height(void) { return 18; }",
        "",
    ]
    for name, pixels in hero:
        lines.extend(emit_array(name, pixels))
    lines.extend(emit_array("SPR_EN_WIZARD", drop_key_fringe(wizard)))
    lines.extend([
        "const uint32_t *zell_kilix_sprite(int direction, int step)",
        "{",
        "    static const uint32_t *const table[4][2] = {",
        "        { SPR_KILIX_DOWN_0, SPR_KILIX_DOWN_1 },",
        "        { SPR_KILIX_UP_0, SPR_KILIX_UP_1 },",
        "        { SPR_KILIX_LEFT_0, SPR_KILIX_LEFT_1 },",
        "        { SPR_KILIX_RIGHT_0, SPR_KILIX_RIGHT_1 },",
        "    };",
        "    if (direction < 0 || direction > 3) direction = 0;",
        "    return table[direction][step & 1];",
        "}",
        "",
        "const uint32_t *zell_wizard_sprite(void)",
        "{",
        "    return SPR_EN_WIZARD;",
        "}",
        "",
    ])
    return "\n".join(lines)


def main():
    root = pathlib.Path(__file__).resolve().parents[1]
    games = root.parents[1] / "games"
    sheet = games / "kilix-land" / "assets" / "graphics" / "casts" / "legend-player.png"
    header = games / "shellda" / "src" / "generated_sprites.h"
    destination = root / "src" / "sprites.c"
    image = Image.open(sheet).convert("RGBA")
    if image.size != (1024, 512):
        raise SystemExit(f"unexpected Kilix sheet size {image.size}")
    hero = [(name, cell_pixels(image, column, row)) for name, column, row in HERO]
    text = header.read_text(encoding="utf-8", errors="replace")
    wizard = extract_sprites.pixels(extract_sprites.array_bytes(text, "SPR_EN_WIZARD"))
    if len(wizard) != 18 * 18:
        raise SystemExit(f"wizard has {len(wizard)} pixels")
    destination.write_text(emit(hero, wizard), encoding="utf-8")


if __name__ == "__main__":
    main()
