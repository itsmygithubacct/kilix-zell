def quiet_alpha(cell):
    """Drop sub-visible alpha and keep the cell's anchor."""
    cell = cell.convert('RGBA')
    cell.putalpha(cell.getchannel('A').point(lambda a: 0 if a <= 3 else a))
    return cell


def fixed_cells(name, columns, rows):
    sheet = Image.open(ROOM_ASSETS / name).convert('RGBA')
    cells = []
    for row in range(rows):
        for col in range(columns):
            cells.append(quiet_alpha(sheet.crop((
                col * sheet.width // columns, row * sheet.height // rows,
                (col + 1) * sheet.width // columns, (row + 1) * sheet.height // rows))))
    return cells


def column_cutouts(name, columns, rows):
    """Cut a sprite grid. Each column shares one alpha bound across its rows.

    Open and closed hatches keep the same scale and horizontal anchor.
    Clear alpha <= 3, then bound the sprite at alpha > 32.
    """
    sheet = Image.open(ROOM_ASSETS / name).convert('RGBA')
    grid = []
    for row in range(rows):
        row_cells = []
        for col in range(columns):
            cell = sheet.crop((
                col * sheet.width // columns, row * sheet.height // rows,
                (col + 1) * sheet.width // columns, (row + 1) * sheet.height // rows))
            cell.putalpha(cell.getchannel('A').point(lambda a: 0 if a <= 3 else a))
            row_cells.append(cell)
        grid.append(row_cells)
    bounds = []
    for col in range(columns):
        boxes = []
        for row in range(rows):
            box = grid[row][col].getchannel('A').point(
                lambda a: 255 if a > 32 else 0).getbbox()
            if box is None:
                raise ValueError('Missing sprite in %s column %d' % (name, col))
            boxes.append(box)
        bounds.append((min(b[0] for b in boxes), min(b[1] for b in boxes),
                       max(b[2] for b in boxes), max(b[3] for b in boxes)))
    return [grid[row][col].crop(bounds[col])
            for row in range(rows) for col in range(columns)]


def hatch_rim_gap(picture):
    """Distance from the solid front stone edge to the bottom of the frame."""
    size, pixels = picture
    alpha = Image.frombytes('L', size, pixels[3::4])
    solid = alpha.point(lambda a: 255 if a >= 128 else 0).getbbox()
    if solid is None:
        raise ValueError('room hatch has no solid rim')
    return size[1] - solid[3]


def open_cave_hatch(closed, opened, well_top, well_bottom, aperture):
    """Hang the new lid behind the original back rail and fit the stairs inside its sill."""
    base = closed.copy()
    width, height = base.size
    paint = opened.convert('RGBa')
    sw, sh = paint.size
    hinge = round(well_top * sh)
    bottom = round(well_bottom * sh)
    mask = Image.new('L', (4 * width, 4 * height))
    ImageDraw.Draw(mask).polygon([(4*x, 4*y) for x, y in aperture], fill=255)
    mask = mask.resize(base.size, Image.Resampling.LANCZOS)
    box = mask.getbbox()
    well = paint.transform((box[2]-box[0], box[3]-box[1]), Image.Transform.QUAD,
                           (.25*sw, hinge, .16*sw, bottom, .84*sw, bottom, .75*sw, hinge),
                           Image.Resampling.BICUBIC)
    base.paste(well, box, mask.crop(box))

    back = aperture[0][1]
    lid_height = round(.42 * width)
    lid = paint.crop((0, 0, sw, hinge)).resize((width, lid_height), Image.Resampling.LANCZOS)
    rise = lid_height - back
    frame = Image.new('RGBA', (width, height + rise))
    frame.paste(lid.convert('RGBA'), (0, 0))
    frame.alpha_composite(base.convert('RGBA'), (0, rise))
    frame = frame.convert('RGBa')
    # Only the back rail overlaps the lid. Below it copy the premultiplied
    # pixels directly so the stone, rivets and front latch are identical.
    frame.paste(base.crop((0, back, width, height)), (0, lid_height))
    return frame


def paint_hatch_panel(frame, panel, top, bottom):
    """Project a flat lid face between two horizontal rails of the stone hatch."""
    left, right, y = top
    end_left, end_right, end_y = bottom
    x = min(left, end_left)
    width, height = max(right, end_right) - x, end_y - y
    scale = 4
    size = (scale * width, scale * height)
    tile = panel.convert('RGBA').resize(size, Image.Resampling.LANCZOS)
    # Pillow maps output pixels back to the tile. The projected width and the
    # left edge both vary linearly from the first rail to the second.
    u = tile.width / (right - left)
    taper = (end_right - end_left) / (right - left)
    inverse = (u / scale, -u * (end_left - left) / size[1], u * (x - left),
               0, taper, 0, 0, (taper - 1) / size[1])
    face = tile.transform(size, Image.Transform.PERSPECTIVE, inverse, Image.Resampling.BICUBIC)
    patch = frame.crop((x, y, x + width, end_y)).convert('RGBA')
    patch.alpha_composite(face.resize((width, height), Image.Resampling.LANCZOS))
    result = frame.copy()
    result.paste(patch.convert('RGBa'), (x, y))
    return result


def sheet_source(name, pictures):
    """One sheet's pictures as C: 64-bit words, then the sheet's table."""
    lines = [MARK, '#include "art.h"\n']
    rows = []
    for i, (size, raw) in enumerate(pictures):
        blob = zlib.compress(raw, 9)
        rows.append('    {%d, %d, %d, image%d},\n' % (*size, len(blob), i))
        # Hex words are a third smaller than a decimal number per byte.
        blob += bytes(-len(blob) % 8)
        packed = struct.unpack('<%dQ' % (len(blob) // 8), blob)
        lines.append('static const uint64_t image%d[] = {\n' % i)
        lines.extend(','.join('0x%016x' % word for word in packed[j:j + 6]) + ',\n'
                     for j in range(0, len(packed), 6))
        lines.append('};\n')
    return ''.join(lines + ['const zell_art_source zell_art_%s[] = {\n' % name] + rows + ['};\n'])


def main():
    heights = [height for _, sheet in SHEETS for height in sheet]
    images = load_images()
    if len(images) != len(heights):
        raise ValueError('Asset dimensions do not match the atlas')
    sheets = {}
    offset = 0
    for name, cells in SHEETS:
        sheets[name] = range(offset, offset + len(cells))
        offset += len(cells)
    vault, workshop = sheets['extra_room_props'][:2]
    command_open, vault_open, workshop_open, laundry_open = sheets['cave_hatches_open']
    for closed, raised, opening in zip((vault, workshop), (vault_open, workshop_open), CAVE_HATCH_OPENINGS):
        source = images[closed]
        height = round(CAVE_HATCH_WIDTH * source.height / source.width)
        width = round(height * source.width / source.height)
        images[closed] = source.convert('RGBa').resize((width, height), Image.Resampling.LANCZOS)
        images[raised] = open_cave_hatch(images[closed], images[raised], *opening)
    # The Workshop supplies both physical poses. Only the panel between its
    # rails changes, so the hinge, stone blocks and stairwell keep their angles.
    for closed, raised in zip(sheets['room_props'][:2], (command_open, laundry_open)):
        panel = images[closed]
        images[closed] = paint_hatch_panel(images[workshop], panel, (29, 107, 24), (22, 113, 70))
        images[raised] = paint_hatch_panel(images[workshop_open], panel, (32, 103, 16), (36, 99, 46))
    room_hatches = sheets['room_hatches']
    for index in room_hatches:
        heights[index] = round(CAVE_HATCH_WIDTH * images[index].height / images[index].width)
        compiled_width = max(1, round(images[index].width * heights[index] / images[index].height))
        if compiled_width != CAVE_HATCH_WIDTH:
            raise ValueError('room hatch width %d != %d' % (compiled_width, CAVE_HATCH_WIDTH))
    compiled = [premultiplied_pixels(im, height) for im, height in zip(images, heights)]
    # Zell draws each frame from its bottom edge. Give the painted stone
    # rim the same margin in both poses, keeping the entire raised lid.
    columns = len(room_hatches) // 2
    for pair in zip(room_hatches[:columns], room_hatches[columns:]):
        gaps = [hatch_rim_gap(compiled[i]) for i in pair]
        for i, gap in zip(pair, gaps):
            (width, height), pixels = compiled[i]
            padding = max(gaps) - gap
            compiled[i] = ((width, height + padding), pixels + bytes(width * padding * 4))
    files = {
        'art.h': HEADER % ''.join('extern const zell_art_source zell_art_%s[];\n' % name
                                  for name, _ in SHEETS),
        'index.c': INDEX % ''.join(
            '    ' + ' '.join('zell_art_%s + %d,' % (name, i)
                              for i in range(first, min(first + 4, len(sheet)))) + '\n'
            for name, sheet in SHEETS for first in range(0, len(sheet), 4)),
    }
    first = 0
    for name, sheet in SHEETS:
        files[name + '.c'] = sheet_source(name, compiled[first:first + len(sheet)])
        first += len(sheet)
    ART.mkdir(exist_ok=True)
    for path in ART.glob('*.[ch]'):
        # A sheet that has left SHEETS must not stay in the build.
        if path.name not in files and path.read_text().startswith(MARK):
            path.unlink()
    for name, text in files.items():
        # Leave unchanged files alone so make does not recompile them.
        if not (ART / name).exists() or (ART / name).read_text() != text:
            (ART / name).write_text(text)


if __name__ == '__main__':
    main()
