HEADER = MARK + '''#ifndef ZELL_DESKTOP_ART_H
#define ZELL_DESKTOP_ART_H
#include <stdint.h>
/* One picture: a zlib stream of premultiplied ARGB, packed eight bytes to a
 * word, low byte first. size counts the stream's bytes. */
typedef struct { int width, height; unsigned long size; const uint64_t *words; } zell_art_source;
%s#endif
'''

INDEX = MARK + '''#include "desktop_assets.h"
#include "art.h"
#include <stdlib.h>
#include <zlib.h>

/* Art ids in order. Each sheet's pictures are in the file named after it. */
static const zell_art_source *const sources[] = {
%s};
_Static_assert(sizeof sources / sizeof *sources == ZELL_ART_COUNT,
               "the art sheets and desktop_assets.h disagree");
static zell_art art[ZELL_ART_COUNT];

const zell_art *zell_art_get(int id) {
    if (id < 0 || id >= ZELL_ART_COUNT) return NULL;
    zell_art *a = &art[id];
    if (a->pixels) return a;
    const zell_art_source *source = sources[id];
    unsigned long size = (unsigned long)source->width * (unsigned long)source->height * 4;
    unsigned char *packed = malloc(source->size);
    uint32_t *pixels = malloc(size);
    if (packed && pixels) {
        /* Unpack by shifting, so the bytes come out the same on any host. */
        for (unsigned long i = 0; i < source->size; i++)
            packed[i] = (unsigned char)(source->words[i / 8] >> (i %% 8 * 8));
        if (uncompress((unsigned char *)pixels, &size, packed, source->size) == Z_OK) {
            free(packed);
            a->width = source->width;
            a->height = source->height;
            a->pixels = pixels;
            return a;
        }
    }
    free(packed);
    free(pixels);
    return NULL;
}
'''


def cutout(cell):
    cell = cell.convert('RGBA')
    # Generated transparent sheets contain sub-visible alpha noise outside
    # the silhouettes. Remove that noise, retaining the actual soft edges.
    cell.putalpha(cell.getchannel('A').point(lambda a: 0 if a <= 3 else a))
    box = cell.getchannel('A').point(lambda a: 255 if a > 32 else 0).getbbox()
    return cell.crop(box) if box else cell


def top_piece(cell):
    """Cut out the first object in a cell, dropping any stray piece below it."""
    cell.putalpha(cell.getchannel('A').point(lambda a: 0 if a <= 3 else a))
    mask = cell.getchannel('A').point(lambda a: 255 if a > 32 else 0)
    box = mask.getbbox()
    if not box:
        return cell
    bottom = box[1]
    while bottom < box[3] and mask.crop((0, bottom, cell.width, bottom + 1)).getbbox():
        bottom += 1
    cell = cell.crop((0, box[1], cell.width, bottom))
    return cell.crop(cell.getchannel('A').point(lambda a: 255 if a > 32 else 0).getbbox())


def premultiplied_pixels(image, height=None):
    image = image.convert('RGBa')
    if height is not None:
        width = max(1, round(image.width * height / image.height))
        image = image.resize((width, height), Image.Resampling.LANCZOS)
    # Lanczos ringing may put a color just above alpha; clamp to the raster
    # contract rather than letting an edge brighten the background.
    raw = b''.join(struct.pack('<I', (a << 24) | (min(r, a) << 16) |
                              (min(g, a) << 8) | min(b, a))
                   for r, g, b, a in image.getdata())
    return image.size, raw


def load_images():
    images = [Image.open(ASSETS / 'cave.png').convert('RGBA')]
    for name in ('cast.png', 'workstations.png'):
        image = Image.open(ASSETS / name).convert('RGBA')
        # The authored cast gutter is above the mathematical midpoint.
        edges = (0, 440 if name == 'cast.png' else image.height // 2,
                 image.height)
        for y in range(2):
            for x in range(4):
                images.append(cutout(image.crop((x * image.width // 4, edges[y],
                                                 (x + 1) * image.width // 4, edges[y + 1]))))
    image = Image.open(ASSETS / 'walk.png').convert('RGBA')
    for y in range(4):
        for x in range(4):
            images.append(cutout(image.crop((x * image.width // 4, y * image.height // 4,
                                             (x + 1) * image.width // 4,
                                             (y + 1) * image.height // 4))))
    images.extend(Image.open(ROOM_ASSETS / name).convert('RGBA')
                  for name in ('command-center.png', 'laundry.png'))
    sheet = Image.open(ROOM_ASSETS / 'room-props.png').convert('RGBA')
    for row in range(2):
        for col in range(4):
            images.append(cutout(sheet.crop((col * sheet.width // 4, row * sheet.height // 2,
                                            (col + 1) * sheet.width // 4,
                                            (row + 1) * sheet.height // 2))))
    frames = []
    for name, rows in (('staff.png', 2), ('key-master.png', 1)):
        sheet = Image.open(ROOM_ASSETS / name).convert('RGBA')
        for row in range(rows):
            frames.append([sheet.crop((col * sheet.width // 4, row * sheet.height // rows,
                                       (col + 1) * sheet.width // 4, (row + 1) * sheet.height // rows))
                           for col in range(4)])
    for cells in frames:
        # Share the crop and scale across an animation: breathing must not
        # change the character's size or shift its feet between frames.
        boxes = []
        for cell in cells:
            cell.putalpha(cell.getchannel('A').point(lambda a: 0 if a <= 3 else a))
            boxes.append(cell.getchannel('A').point(lambda a: 255 if a > 32 else 0).getbbox())
        if any(box is None for box in boxes):
            raise ValueError('Missing staff animation frame')
        bounds = (min(b[0] for b in boxes), min(b[1] for b in boxes),
                  max(b[2] for b in boxes), max(b[3] for b in boxes))
        images.extend(cell.crop(bounds) for cell in cells)
    sheet = Image.open(ROOM_ASSETS/'weather.png').convert('RGBA')
    for row in range(2):
        for col in range(4):
            images.append(cutout(sheet.crop((col*sheet.width//4, row*sheet.height//2,
                                            (col+1)*sheet.width//4, (row+1)*sheet.height//2))))
    for name in ('civic-staff-clean.png','craft-staff.png'):
        sheet=Image.open(ROOM_ASSETS/name).convert('RGBA')
        for row in range(5):
            cells=[sheet.crop((col*sheet.width//4,row*sheet.height//5,(col+1)*sheet.width//4,(row+1)*sheet.height//5)) for col in range(4)]
            boxes=[]
            for cell in cells:
                cell.putalpha(cell.getchannel('A').point(lambda a:0 if a<=3 else a))
                boxes.append(cell.getchannel('A').point(lambda a:255 if a>32 else 0).getbbox())
            if any(b is None for b in boxes):raise ValueError('Missing OS staff frame')
            bounds=(min(b[0] for b in boxes),min(b[1] for b in boxes),max(b[2] for b in boxes),max(b[3] for b in boxes))
            images.extend(cell.crop(bounds) for cell in cells)
    images.extend(Image.open(ROOM_ASSETS/name).convert('RGBA') for name in ('vault.png','workshop.png'))
    sheet=Image.open(ROOM_ASSETS/'extra-room-props.png').convert('RGBA')
    for row in range(2):
        for col in range(2):images.append((cutout if row else top_piece)(sheet.crop((col*sheet.width//2,row*sheet.height//2,(col+1)*sheet.width//2,(row+1)*sheet.height//2))))
    images.extend(fixed_cells('command-floor-panels.png', 4, 2))
    images.extend(fixed_cells('command-monitor-frames.png', 2, 1))
    images.extend(fixed_cells('mana-check-button.png', 3, 2))
    images.append(quiet_alpha(Image.open(ROOM_ASSETS / 'workshop-stool-overlay.png')))
    images.extend(Image.open(ROOM_ASSETS / name).convert('RGBA') for name in (
        'game-room.png', 'movie-theater.png', 'meditation-room.png', 'library-room.png'))
    images.extend(quiet_alpha(Image.open(ROOM_ASSETS / name)) for name in (
        'game-room-foreground.png', 'movie-theater-foreground.png',
        'meditation-room-foreground.png', 'library-room-foreground.png'))
    images.extend(column_cutouts('room-hatches.png', 4, 2))
    return images


def quiet_alpha(cell):
    """Drop sub-visible alpha and keep the cell's anchor."""
    cell = cell.convert('RGBA')
    cell.putalpha(cell.getchannel('A').point(lambda a: 0 if a <= 3 else a))
    return cell


def fixed_cells(name, columns, rows):
    sheet = Image.open(ROOM_ASSETS / name).convert('RGBA')
    cells = []
    for row in range(rows):
        for col in range(columns):
            cells.append(quiet_alpha(sheet.crop((
                col * sheet.width // columns, row * sheet.height // rows,
                (col + 1) * sheet.width // columns, (row + 1) * sheet.height // rows))))
    return cells


def column_cutouts(name, columns, rows):
    """Cut a sprite grid. Each column shares one alpha bound across its rows.

    An open hatch and its closed hatch then keep the same anchor. Alpha
    matches cutout: clear alpha <= 3, then bound the sprite at alpha > 32.
    """
    sheet = Image.open(ROOM_ASSETS / name).convert('RGBA')
    grid = []
    for row in range(rows):
        row_cells = []
        for col in range(columns):
            cell = sheet.crop((
                col * sheet.width // columns, row * sheet.height // rows,
                (col + 1) * sheet.width // columns, (row + 1) * sheet.height // rows))
            cell.putalpha(cell.getchannel('A').point(lambda a: 0 if a <= 3 else a))
            row_cells.append(cell)
        grid.append(row_cells)
    bounds = []
    for col in range(columns):
        boxes = []
        for row in range(rows):
            box = grid[row][col].getchannel('A').point(
                lambda a: 255 if a > 32 else 0).getbbox()
            if box is None:
                raise ValueError('Missing sprite in %s column %d' % (name, col))
            boxes.append(box)
        bounds.append((min(b[0] for b in boxes), min(b[1] for b in boxes),
                       max(b[2] for b in boxes), max(b[3] for b in boxes)))
    return [grid[row][col].crop(bounds[col])
            for row in range(rows) for col in range(columns)]


def sheet_source(name, pictures):
    """One sheet's pictures as C: 64-bit words, then the sheet's table."""
    lines = [MARK, '#include "art.h"\n']
    rows = []
    for i, (size, raw) in enumerate(pictures):
        blob = zlib.compress(raw, 9)
        rows.append('    {%d, %d, %d, image%d},\n' % (*size, len(blob), i))
        # Hex words are a third smaller than a decimal number per byte.
        blob += bytes(-len(blob) % 8)
        packed = struct.unpack('<%dQ' % (len(blob) // 8), blob)
        lines.append('static const uint64_t image%d[] = {\n' % i)
        lines.extend(','.join('0x%016x' % word for word in packed[j:j + 6]) + ',\n'
                     for j in range(0, len(packed), 6))
        lines.append('};\n')
    return ''.join(lines + ['const zell_art_source zell_art_%s[] = {\n' % name] + rows + ['};\n'])


def main():
    heights = [height for _, sheet in SHEETS for height in sheet]
    images = load_images()
    # The four cave hatches are drawn at one width. The Vault and Workshop
    # hatches are squarer than the first two, so they are taller at that width.
    # The extra-room hatches share the command hatch's width. Find them by
    # sheet so later sheets do not move these two indexes.
    index = 0
    extra_hatches = None
    for name, sheet in SHEETS:
        if name == 'extra_room_props':
            extra_hatches = (index, index + 1)
            break
        index += len(sheet)
    if extra_hatches is None:
        raise ValueError('extra room hatches are not in the atlas')
    command = heights.index(76)
    width = images[command].width * 76 / images[command].height
    for index in extra_hatches:
        heights[index] = round(width * images[index].height / images[index].width)
    if len(images) != len(heights):
        raise ValueError('Asset dimensions do not match the atlas')
    sheet_at = 0
    room_hatches = None
    for name, sheet in SHEETS:
        if name == 'room_hatches':
            room_hatches = range(sheet_at, sheet_at + len(sheet))
            break
        sheet_at += len(sheet)
    if room_hatches is None:
        raise ValueError('room hatches are not in the atlas')
    command_width = max(1, round(images[command].width * heights[command] / images[command].height))
    for index in room_hatches:
        heights[index] = round(width * images[index].height / images[index].width)
        compiled_width = max(1, round(images[index].width * heights[index] / images[index].height))
        if compiled_width != command_width:
            raise ValueError('room hatch width %d != command hatch width %d'
                             % (compiled_width, command_width))
    compiled = [premultiplied_pixels(im, height) for im, height in zip(images, heights)]
    files = {
        'art.h': HEADER % ''.join('extern const zell_art_source zell_art_%s[];\n' % name
                                  for name, _ in SHEETS),
        'index.c': INDEX % ''.join(
            '    ' + ' '.join('zell_art_%s + %d,' % (name, i)
                              for i in range(first, min(first + 4, len(sheet)))) + '\n'
            for name, sheet in SHEETS for first in range(0, len(sheet), 4)),
    }
    first = 0
    for name, sheet in SHEETS:
        files[name + '.c'] = sheet_source(name, compiled[first:first + len(sheet)])
        first += len(sheet)
    ART.mkdir(exist_ok=True)
    for path in ART.glob('*.[ch]'):
        # A sheet that has left SHEETS must not stay in the build.
        if path.name not in files and path.read_text().startswith(MARK):
            path.unlink()
    for name, text in files.items():
        # Leave unchanged files alone so make does not recompile them.
        if not (ART / name).exists() or (ART / name).read_text() != text:
            (ART / name).write_text(text)


if __name__ == '__main__':
    main()
