#!/usr/bin/env python3
"""Restore Clink's walk cycle and the cave wizard from Shellda's sprite header.

The shipped hero is Kilix Land's legend cast. tools/paint_kilix.py writes
that file. This script puts Clink's frames back and still emits
zell_sprite_width, which src/sprites.h no longer declares. Do not run it
against the current tree.
"""

import pathlib
import re
import sys

NAMES = (
    "SPR_CLINK_DOWN_0",
    "SPR_CLINK_DOWN_1",
    "SPR_CLINK_UP_0",
    "SPR_CLINK_UP_1",
    "SPR_CLINK_LEFT_0",
    "SPR_CLINK_LEFT_1",
    "SPR_CLINK_RIGHT_0",
    "SPR_CLINK_RIGHT_1",
    "SPR_EN_WIZARD",
)


def array_bytes(text, name):
    match = re.search(
        r"static const unsigned char %s\[\] = \{(.*?)\};" % name,
        text,
        re.S,
    )
    if match is None:
        raise SystemExit(f"missing {name}")
    values = [int(item) for item in re.findall(r"\d+", match.group(1))]
    if len(values) % 4 != 0:
        raise SystemExit(f"{name} is not RGBA")
    return values


def pixels(values):
    out = []
    for index in range(0, len(values), 4):
        red, green, blue, alpha = values[index:index + 4]
        out.append((alpha << 24) | (red << 16) | (green << 8) | blue)
    return out


def emit(sprites, width, height):
    lines = [
        "/* Generated by tools/extract_sprites.py. Do not edit by hand.",
        " * Pixel bytes from Shellda src/generated_sprites.h",
        " * (MIT, Copyright (c) 2026 shellda contributors).",
        " * Frames come from the Gemini sheets clink_walk_gemini_sheet_v2.png",
        " * and enemies_gemini_sheet.png. Alpha is 0 or 255.",
        " */",
        '#include "sprites.h"',
        "",
        f"int zell_sprite_width(void) {{ return {width}; }}",
        f"int zell_sprite_height(void) {{ return {height}; }}",
        "",
    ]
    for name, pixels_ in sprites:
        lines.append(
            f"static const uint32_t {name}[{len(pixels_)}] = {{"
        )
        row = []
        for pixel in pixels_:
            row.append(f"0x{pixel:08x}u")
            if len(row) == 8:
                lines.append("    " + ", ".join(row) + ",")
                row = []
        if row:
            lines.append("    " + ", ".join(row) + ",")
        lines.append("};")
        lines.append("")
    lines.append("const uint32_t *zell_kilix_sprite(int direction, int step)")
    lines.append("{")
    lines.append("    static const uint32_t *const table[4][2] = {")
    lines.append("        { SPR_CLINK_DOWN_0, SPR_CLINK_DOWN_1 },")
    lines.append("        { SPR_CLINK_UP_0, SPR_CLINK_UP_1 },")
    lines.append("        { SPR_CLINK_LEFT_0, SPR_CLINK_LEFT_1 },")
    lines.append("        { SPR_CLINK_RIGHT_0, SPR_CLINK_RIGHT_1 },")
    lines.append("    };")
    lines.append("    if (direction < 0 || direction > 3) direction = 0;")
    lines.append("    return table[direction][step & 1];")
    lines.append("}")
    lines.append("")
    lines.append("const uint32_t *zell_wizard_sprite(void)")
    lines.append("{")
    lines.append("    return SPR_EN_WIZARD;")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def main():
    source = pathlib.Path(sys.argv[1])
    destination = pathlib.Path(sys.argv[2])
    text = source.read_text(encoding="utf-8", errors="replace")
    width = int(re.search(r"#define CLINK_SPRITE_W (\d+)", text).group(1))
    height = int(re.search(r"#define CLINK_SPRITE_H (\d+)", text).group(1))
    enemy_w = int(re.search(r"#define ENEMY_SPRITE_W (\d+)", text).group(1))
    enemy_h = int(re.search(r"#define ENEMY_SPRITE_H (\d+)", text).group(1))
    if (enemy_w, enemy_h) != (width, height):
        raise SystemExit("wizard sprite size does not match Clink")
    sprites = []
    expected = width * height
    for name in NAMES:
        converted = pixels(array_bytes(text, name))
        if len(converted) != expected:
            raise SystemExit(f"{name} has {len(converted)} pixels, want {expected}")
        sprites.append((name, converted))
    destination.write_text(emit(sprites, width, height), encoding="utf-8")


if __name__ == "__main__":
    main()
