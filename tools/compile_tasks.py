"""Keep native action names and the private task registry in the same order."""
from pathlib import Path
import json
import zell_os


def render():
    return '/* Generated by tools/compile_tasks.py. */\n'+''.join(
        f' [{station}]={{'+','.join(json.dumps(label) for label,_ in zell_os.entries(group))+',NULL},\n'
        for station,group in zell_os.STATIONS.items())


if __name__=='__main__':
    (Path(__file__).resolve().parents[1]/'src/os_tasks.inc').write_text(render())
