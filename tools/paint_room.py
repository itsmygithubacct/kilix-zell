#!/usr/bin/env python3
"""Copy Shellda's cave tiles and Legend of Kilix's campfire into src/room.c."""

import pathlib
import re

from PIL import Image

TILES = (
    ("TILE_STONE", "SPR_TILE_STONE"),
    ("TILE_WALL", "SPR_TILE_ROCK_WALL"),
    ("TILE_DARK", "SPR_TILE_DARK"),
    ("TILE_STAIRS", "SPR_TILE_STAIRS_UP"),
)
TILE_EDGE = 16
FIRE_EDGE = 64
EMBER_ROWS = 18


def pixels_from_rgba(values):
    pixels = []
    for index in range(0, len(values), 4):
        red, green, blue, alpha = values[index:index + 4]
        if alpha < 128:
            pixels.append(0)
        else:
            pixels.append((0xFF << 24) | (red << 16) | (green << 8) | blue)
    return pixels


def array_bytes(text, name):
    match = re.search(
        r"static const unsigned char %s\[\] = \{(.*?)\};" % name,
        text,
        re.S,
    )
    if match is None:
        raise SystemExit(f"missing {name}")
    return [int(item) for item in re.findall(r"\d+", match.group(1))]


def is_flame(pixel):
    if pixel == 0:
        return False
    red = (pixel >> 16) & 255
    green = (pixel >> 8) & 255
    blue = pixel & 255
    return red > 170 and red > blue + 30 and red + 20 > green


def mirror_flame(pixels):
    """Flip flame pixels only. The log ring stays on the same pixels."""
    mirrored = list(pixels)
    for y in range(FIRE_EDGE):
        for x in range(FIRE_EDGE // 2):
            left = y * FIRE_EDGE + x
            right = y * FIRE_EDGE + (FIRE_EDGE - 1 - x)
            a = pixels[left]
            b = pixels[right]
            if is_flame(a) and is_flame(b):
                mirrored[left], mirrored[right] = b, a
            elif is_flame(a) and b == 0:
                mirrored[right] = a
                mirrored[left] = 0
            elif is_flame(b) and a == 0:
                mirrored[left] = b
                mirrored[right] = 0
    return mirrored


def nudge_embers(pixels, dx):
    """Slide the tip and the sparks sideways. Log pixels stay where they are."""
    nudged = list(pixels)
    for y in range(EMBER_ROWS):
        for x in range(FIRE_EDGE):
            if is_flame(pixels[y * FIRE_EDGE + x]):
                nudged[y * FIRE_EDGE + x] = 0
    for y in range(EMBER_ROWS):
        for x in range(FIRE_EDGE):
            pixel = pixels[y * FIRE_EDGE + x]
            next_x = x + dx
            if not is_flame(pixel) or not 0 <= next_x < FIRE_EDGE:
                continue
            dest = y * FIRE_EDGE + next_x
            if pixels[dest] and not is_flame(pixels[dest]):
                continue
            nudged[dest] = pixel
    return nudged


def emit_array(name, pixels):
    lines = [f"static const uint32_t {name}[{len(pixels)}] = {{"]
    row = []
    for pixel in pixels:
        row.append(f"0x{pixel:08x}u")
        if len(row) == 8:
            lines.append("    " + ", ".join(row) + ",")
            row = []
    if row:
        lines.append("    " + ", ".join(row) + ",")
    lines.append("};")
    lines.append("")
    return lines


def main():
    root = pathlib.Path(__file__).resolve().parents[1]
    games = root.parents[1] / "games"
    tiles = (games / "shellda" / "src" / "generated_tiles.h").read_text(
        encoding="utf-8", errors="replace")
    sprites = (games / "shellda" / "src" / "generated_sprites.h").read_text(
        encoding="utf-8", errors="replace")
    sheet = Image.open(
        games / "legend-of-kilix" / "assets" / "graphics" / "effects" / "vfx.png"
    ).convert("RGBA")
    campfire = sheet.crop((4 * FIRE_EDGE, FIRE_EDGE, 5 * FIRE_EDGE, 2 * FIRE_EDGE))
    if campfire.size != (FIRE_EDGE, FIRE_EDGE):
        raise SystemExit(f"campfire cell is {campfire.size}")

    arrays = []
    for local_name, source_name in TILES:
        pixels = pixels_from_rgba(array_bytes(tiles, source_name))
        if len(pixels) != TILE_EDGE * TILE_EDGE:
            raise SystemExit(f"{source_name} has {len(pixels)} pixels")
        arrays.append((local_name, pixels))
    heart = pixels_from_rgba(array_bytes(sprites, "SPR_DROP_HEART"))
    if len(heart) != 16 * 16:
        raise SystemExit(f"SPR_DROP_HEART has {len(heart)} pixels")
    arrays.append(("HEART", heart))
    fire_pixels = []
    for red, green, blue, alpha in campfire.getdata():
        if alpha < 128:
            fire_pixels.append(0)
        else:
            fire_pixels.append((0xFF << 24) | (red << 16) | (green << 8) | blue)
    if len(fire_pixels) != FIRE_EDGE * FIRE_EDGE:
        raise SystemExit(f"campfire has {len(fire_pixels)} pixels")
    mirrored = mirror_flame(fire_pixels)
    arrays.append(("CAMPFIRE", fire_pixels))
    arrays.append(("CAMPFIRE_1", mirrored))
    arrays.append(("CAMPFIRE_2", nudge_embers(fire_pixels, 1)))
    arrays.append(("CAMPFIRE_3", nudge_embers(mirrored, -1)))

    lines = [
        "/* Generated by tools/paint_room.py. Do not edit by hand.",
        " * Tiles are Shellda's cave set from src/generated_tiles.h.",
        " * HEART is Shellda's SPR_DROP_HEART.",
        " * Shellda is MIT, Copyright (c) 2026 shellda contributors.",
        " * The campfire is one cell of Legend of Kilix effects/vfx.png",
        " * (MIT, Copyright (c) 2026 itsmygithubacct). The extra frames",
        " * mirror that cell's flame and slide its sparks. The logs stay.",
        " */",
        '#include "room.h"',
        "",
        "int zell_tile_edge(void) { return 16; }",
        "int zell_heart_edge(void) { return 16; }",
        "int zell_campfire_edge(void) { return 64; }",
        "int zell_campfire_frames(void) { return 4; }",
        "",
    ]
    for name, pixels in arrays:
        lines.extend(emit_array(name, pixels))
    lines.extend([
        "const uint32_t *zell_tile_stone(void) { return TILE_STONE; }",
        "const uint32_t *zell_tile_wall(void) { return TILE_WALL; }",
        "const uint32_t *zell_tile_dark(void) { return TILE_DARK; }",
        "const uint32_t *zell_tile_stairs(void) { return TILE_STAIRS; }",
        "const uint32_t *zell_heart(void) { return HEART; }",
        "const uint32_t *zell_campfire(void) { return CAMPFIRE; }",
        "",
        "const uint32_t *zell_campfire_frame(int frame)",
        "{",
        "    switch (frame) {",
        "    case 1: return CAMPFIRE_1;",
        "    case 2: return CAMPFIRE_2;",
        "    case 3: return CAMPFIRE_3;",
        "    default: return CAMPFIRE;",
        "    }",
        "}",
        "",
    ])
    destination = root / "src" / "room.c"
    destination.write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
